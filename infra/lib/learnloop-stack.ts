import path from 'node:path';
import {
  Aws, CfnOutput, CfnParameter, DockerImage, Duration, RemovalPolicy, Stack, type StackProps,
} from 'aws-cdk-lib';
import * as apigw from 'aws-cdk-lib/aws-apigatewayv2';
import { HttpLambdaIntegration } from 'aws-cdk-lib/aws-apigatewayv2-integrations';
import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';
import * as origins from 'aws-cdk-lib/aws-cloudfront-origins';
import * as events from 'aws-cdk-lib/aws-events';
import * as targets from 'aws-cdk-lib/aws-events-targets';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import { NodejsFunction, OutputFormat } from 'aws-cdk-lib/aws-lambda-nodejs';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as secretsmanager from 'aws-cdk-lib/aws-secretsmanager';
import * as ssm from 'aws-cdk-lib/aws-ssm';
import type { Construct } from 'constructs';
import { REPO_ROOT, SERVICES, serviceEntry } from './services.js';

const PREFIX = 'learnloop-prod';
const RETENTION = logs.RetentionDays.THREE_MONTHS; // 90 days
const LOG_BUCKET_DAYS = 120;
/**
 * Function timeouts. API requests are cut at 10 s by the shared handler
 * whatever the function timeout is; a longer timeout only gives scheduled
 * jobs on that function more time (learning: re-engagement nudges).
 */
const DEFAULT_TIMEOUT_SECONDS = 10;
export const FUNCTION_TIMEOUT_SECONDS: Record<string, number> = { learning: 120 };
export const CLOUDFRONT_LOG_PREFIX = 'cloudfront/';

export const PARAMETER_NAMES = {
  flags: '/learnloop/prod/feature-flags',
} as const;

export const SECRET_NAMES = {
  jwtSecret: 'learnloop/prod/jwt-secret',
  salt: 'learnloop/prod/log-pseudonym-salt',
} as const;

export interface LearnLoopStackProps extends StackProps {
  appVersion: string;
}

export class LearnLoopStack extends Stack {
  constructor(scope: Construct, id: string, props: LearnLoopStackProps) {
    super(scope, id, props);

    // ------------------------------------------------------------ parameters
    const sesSender = new CfnParameter(this, 'sesSender', {
      type: 'String',
      description: 'SES sender address for transactional email (verified by the operator in the SES console)',
    });
    const recipientOverride = new CfnParameter(this, 'emailRecipientOverride', {
      type: 'String', default: '', description: 'Optional: send every email to this verified address (SES sandbox)',
    });

    // ------------------------------------------------------------ buckets
    const bucketDefaults = {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      removalPolicy: RemovalPolicy.RETAIN,
    };
    const webBucket = new s3.Bucket(this, 'WebBucket', { ...bucketDefaults, bucketName: `${PREFIX}-web-${Aws.ACCOUNT_ID}` });
    const stateBucket = new s3.Bucket(this, 'StateBucket', { ...bucketDefaults, bucketName: `${PREFIX}-state-${Aws.ACCOUNT_ID}` });
    // CloudFront standard logging needs ACLs enabled (BucketOwnerPreferred) and SSE-S3, not KMS.
    const accessLogsBucket = new s3.Bucket(this, 'AccessLogsBucket', {
      ...bucketDefaults,
      bucketName: `${PREFIX}-access-logs-${Aws.ACCOUNT_ID}`,
      encryption: s3.BucketEncryption.S3_MANAGED,
      objectOwnership: s3.ObjectOwnership.BUCKET_OWNER_PREFERRED,
      lifecycleRules: [{ id: 'expire-access-logs', expiration: Duration.days(LOG_BUCKET_DAYS) }],
    });
    const appLogsBucket = new s3.Bucket(this, 'AppLogsBucket', {
      ...bucketDefaults,
      bucketName: `${PREFIX}-app-logs-${Aws.ACCOUNT_ID}`,
      lifecycleRules: [{ id: 'expire-app-logs', expiration: Duration.days(LOG_BUCKET_DAYS) }],
    });

    // ------------------------------------------------------------ SSM parameters
    const flagsParameter = new ssm.StringParameter(this, 'FeatureFlags', {
      parameterName: PARAMETER_NAMES.flags,
      description: 'LearnLoop feature flags: { "<flagKey>": { "enabled": bool } }',
      stringValue: JSON.stringify({ new_catalog_filters: { enabled: true } }),
      tier: ssm.ParameterTier.STANDARD,
    });

    // ------------------------------------------------------------ secrets (generated by Secrets Manager)
    const generated = { passwordLength: 64, excludePunctuation: true, includeSpace: false };
    const jwtSecret = new secretsmanager.Secret(this, 'JwtSecret', {
      secretName: SECRET_NAMES.jwtSecret,
      description: 'HMAC-SHA256 key for LearnLoop session tokens',
      generateSecretString: generated,
    });
    const saltSecret = new secretsmanager.Secret(this, 'LogPseudonymSalt', {
      secretName: SECRET_NAMES.salt,
      description: 'Salt for pseudonymised user and session ids in LearnLoop logs',
      generateSecretString: generated,
    });

    // ------------------------------------------------------------ Lambda
    // First iteration: one shared execution role with AdministratorAccess.
    // Per-service least-privilege roles are a later hardening step (see README).
    const role = new iam.Role(this, 'LambdaRole', {
      roleName: `${PREFIX}-lambda-role`,
      assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com'),
      managedPolicies: [iam.ManagedPolicy.fromAwsManagedPolicyName('AdministratorAccess')],
    });

    const environment = {
      APP_ENV: 'prod',
      APP_VERSION: props.appVersion,
      STATE_BUCKET: stateBucket.bucketName,
      FLAGS_PARAMETER: PARAMETER_NAMES.flags,
      LOG_PSEUDONYM_SALT_PARAMETER: SECRET_NAMES.salt, // Secrets Manager secret name
      JWT_SECRET_PARAMETER: SECRET_NAMES.jwtSecret, // Secrets Manager secret name
      SES_SENDER: sesSender.valueAsString,
      EMAIL_RECIPIENT_OVERRIDE: recipientOverride.valueAsString,
      SEED_DIR: '/var/task/seed',
    };

    const api = new apigw.HttpApi(this, 'HttpApi', { apiName: PREFIX, createDefaultStage: true });
    const apiAccessLogs = new logs.LogGroup(this, 'ApiAccessLogs', {
      logGroupName: `/aws/apigateway/${PREFIX}`,
      retention: RETENTION,
      removalPolicy: RemovalPolicy.DESTROY,
    });
    const stage = api.defaultStage!.node.defaultChild as apigw.CfnStage;
    stage.accessLogSettings = {
      destinationArn: apiAccessLogs.logGroupArn,
      format: JSON.stringify({
        requestId: '$context.requestId',
        ip: '$context.identity.sourceIp',
        requestTime: '$context.requestTime',
        httpMethod: '$context.httpMethod',
        routeKey: '$context.routeKey',
        status: '$context.status',
        responseLatency: '$context.responseLatency',
        responseLength: '$context.responseLength',
        userAgent: '$context.identity.userAgent',
        protocol: '$context.protocol',
        integrationLatency: '$context.integrationLatency',
      }),
    };

    const functions: Record<string, NodejsFunction> = {};
    for (const [service, routes] of Object.entries(SERVICES)) {
      const logGroup = new logs.LogGroup(this, `${service}LogGroup`, {
        logGroupName: `/aws/lambda/${PREFIX}-${service}`,
        retention: RETENTION,
        removalPolicy: RemovalPolicy.DESTROY,
      });
      const fn = new NodejsFunction(this, `${service}Function`, {
        functionName: `${PREFIX}-${service}`,
        description: `LearnLoop ${service} service`,
        entry: serviceEntry(service),
        handler: 'handler',
        projectRoot: REPO_ROOT,
        depsLockFilePath: path.join(REPO_ROOT, 'package-lock.json'),
        runtime: lambda.Runtime.NODEJS_22_X,
        architecture: lambda.Architecture.ARM_64,
        memorySize: 512,
        timeout: Duration.seconds(FUNCTION_TIMEOUT_SECONDS[service] ?? DEFAULT_TIMEOUT_SECONDS),
        role,
        logGroup,
        loggingFormat: lambda.LoggingFormat.JSON,
        environment,
        bundling: {
          format: OutputFormat.ESM,
          target: 'node22',
          mainFields: ['module', 'main'],
          externalModules: ['@aws-sdk/*'],
          banner: "import { createRequire } from 'module'; const require = createRequire(import.meta.url);",
          // Bundling runs locally with esbuild (an infra devDependency). Naming an image
          // stops CDK from building one with Docker at synth time when esbuild is absent.
          dockerImage: DockerImage.fromRegistry(lambda.Runtime.NODEJS_22_X.bundlingImage.image),
          commandHooks: {
            beforeBundling: () => [],
            beforeInstall: () => [],
            // The seed data is the initial state; it is copied into the bucket on first use.
            afterBundling: (inputDir: string, outputDir: string) => [`cp -r "${inputDir}/data/seed" "${outputDir}/seed"`],
          },
        },
      });
      functions[service] = fn;
      const integration = new HttpLambdaIntegration(`${service}Integration`, fn);
      for (const route of routes) {
        api.addRoutes({ path: route.path, methods: [apigw.HttpMethod[route.method]], integration });
      }
    }

    new events.Rule(this, 'RenewalSchedule', {
      ruleName: `${PREFIX}-renew-subscriptions`,
      description: 'Daily subscription renewals (mock payments)',
      schedule: events.Schedule.cron({ minute: '10', hour: '0' }),
      targets: [new targets.LambdaFunction(functions.billing, { event: events.RuleTargetInput.fromObject({ job: 'renew_subscriptions' }) })],
    });

    // ------------------------------------------------------------ CloudFront
    const spaRewrite = new cloudfront.Function(this, 'SpaRewrite', {
      functionName: `${PREFIX}-spa-rewrite`,
      comment: 'Serve index.html for client-side routes',
      runtime: cloudfront.FunctionRuntime.JS_2_0,
      code: cloudfront.FunctionCode.fromInline([
        'function handler(event) {',
        '  var request = event.request;',
        "  if (request.uri.indexOf('.') === -1) { request.uri = '/index.html'; }",
        '  return request;',
        '}',
      ].join('\n')),
    });

    const distribution = new cloudfront.Distribution(this, 'Distribution', {
      comment: 'LearnLoop web app and API',
      defaultRootObject: 'index.html',
      priceClass: cloudfront.PriceClass.PRICE_CLASS_100,
      httpVersion: cloudfront.HttpVersion.HTTP2,
      enableLogging: true,
      logBucket: accessLogsBucket,
      logFilePrefix: CLOUDFRONT_LOG_PREFIX,
      logIncludesCookies: false,
      defaultBehavior: {
        origin: origins.S3BucketOrigin.withOriginAccessControl(webBucket),
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        cachePolicy: cloudfront.CachePolicy.CACHING_OPTIMIZED,
        compress: true,
        functionAssociations: [{ function: spaRewrite, eventType: cloudfront.FunctionEventType.VIEWER_REQUEST }],
      },
      additionalBehaviors: {
        '/api/*': {
          origin: new origins.HttpOrigin(`${api.apiId}.execute-api.${Aws.REGION}.amazonaws.com`),
          viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.HTTPS_ONLY,
          allowedMethods: cloudfront.AllowedMethods.ALLOW_ALL,
          cachePolicy: cloudfront.CachePolicy.CACHING_DISABLED,
          originRequestPolicy: cloudfront.OriginRequestPolicy.ALL_VIEWER_EXCEPT_HOST_HEADER,
          compress: true,
        },
      },
    });

    // ------------------------------------------------------------ outputs (read by the deploy workflow and operator tooling)
    const outputs: Record<string, string> = {
      DistributionId: distribution.distributionId,
      DistributionDomainName: distribution.distributionDomainName,
      WebBucketName: webBucket.bucketName,
      StateBucketName: stateBucket.bucketName,
      AccessLogsBucketName: accessLogsBucket.bucketName,
      AppLogsBucketName: appLogsBucket.bucketName,
      ApiEndpoint: api.apiEndpoint,
      CloudFrontLogPrefix: CLOUDFRONT_LOG_PREFIX,
      FeatureFlagsParameter: flagsParameter.parameterName,
      JwtSecretName: jwtSecret.secretName,
      LogPseudonymSaltSecretName: saltSecret.secretName,
    };
    for (const [key, value] of Object.entries(outputs)) new CfnOutput(this, key, { value });
  }
}
